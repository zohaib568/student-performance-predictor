import streamlit as st
import pandas as pd
import joblib
import os

st.set_page_config(page_title="Student Performance Predictor", page_icon="🎓", layout="centered")

# ==============================================================
# Load model + encoders
# ==============================================================
@st.cache_resource
def load_artifacts():
    model = joblib.load("best_model.pkl")
    encoders = joblib.load("encoders.pkl")
    target_le = joblib.load("target_encoder.pkl")
    return model, encoders, target_le

try:
    model, encoders, target_le = load_artifacts()
except FileNotFoundError:
    st.error(
        "Model files not found. Please run `student_performance_predictor.py` "
        "first to generate best_model.pkl, encoders.pkl, and target_encoder.pkl "
        "in this same folder."
    )
    st.stop()

# ==============================================================
# Header
# ==============================================================
st.title("🎓 AI-Based Student Performance Predictor")
st.markdown(
    "Enter a student's profile below to predict their likely final grade, "
    "based on study habits, attendance, and background — **before any exam scores exist.**"
)
st.divider()

# ==============================================================
# Input form
# ==============================================================
col1, col2 = st.columns(2)

with col1:
    age = st.slider("Age", min_value=13, max_value=20, value=16)
    gender = st.selectbox("Gender", encoders['gender'].classes_)
    school_type = st.selectbox("School Type", encoders['school_type'].classes_)
    parent_education = st.selectbox("Parent Education", encoders['parent_education'].classes_)
    study_hours = st.slider("Daily Study Hours", 0.0, 10.0, 3.0, step=0.5)

with col2:
    attendance_percentage = st.slider("Attendance %", 0, 100, 80)
    internet_access = st.selectbox("Internet Access", encoders['internet_access'].classes_)
    travel_time = st.selectbox("Travel Time to School", encoders['travel_time'].classes_)
    extra_activities = st.selectbox("Extra-Curricular Activities", encoders['extra_activities'].classes_)
    study_method = st.selectbox("Preferred Study Method", encoders['study_method'].classes_)

st.divider()

# ==============================================================
# Predict button
# ==============================================================
if st.button("🔮 Predict Grade", use_container_width=True, type="primary"):

    raw_input = {
        'age': age,
        'gender': gender,
        'school_type': school_type,
        'parent_education': parent_education,
        'study_hours': study_hours,
        'attendance_percentage': attendance_percentage,
        'internet_access': internet_access,
        'travel_time': travel_time,
        'extra_activities': extra_activities,
        'study_method': study_method,
    }

    # Encode categorical fields using the saved encoders
    encoded_input = raw_input.copy()
    for col, le in encoders.items():
        encoded_input[col] = le.transform([raw_input[col]])[0]

    input_df = pd.DataFrame([encoded_input])
    # Ensure column order matches training
    input_df = input_df[['age', 'gender', 'school_type', 'parent_education',
                          'study_hours', 'attendance_percentage', 'internet_access',
                          'travel_time', 'extra_activities', 'study_method']]

    pred_encoded = model.predict(input_df)[0]
    pred_grade = target_le.inverse_transform([pred_encoded])[0]

    proba = model.predict_proba(input_df)[0]
    proba_df = pd.DataFrame({
        'Grade': target_le.classes_,
        'Probability': proba
    }).sort_values('Probability', ascending=False)

    st.success(f"### Predicted Final Grade: **{pred_grade.upper()}**")

    st.bar_chart(proba_df.set_index('Grade'))

    # ==============================================================
    # Optional: AI-generated recommendation via Claude
    # ==============================================================
    st.divider()
    st.subheader("💡 Personalized Recommendation")

    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        st.info(
            "Set the `ANTHROPIC_API_KEY` environment variable to enable "
            "AI-generated personalized study advice here."
        )
    else:
        try:
            import anthropic
            client = anthropic.Anthropic(api_key=api_key)
            prompt = f"""You are an academic advisor. A machine learning model predicts this
student will get grade '{pred_grade}' (scale: a=best, f=worst) based on
their profile: {raw_input}

In 3-4 short sentences, written in a warm and encouraging tone:
1. Briefly explain the most likely reason(s) for this predicted grade.
2. Give 2 concrete, specific suggestions the student could act on this week.
Keep it concise, no generic advice like 'work hard'."""

            with st.spinner("Generating personalized advice..."):
                response = client.messages.create(
                    model="claude-sonnet-4-6",
                    max_tokens=300,
                    messages=[{"role": "user", "content": prompt}]
                )
            st.write(response.content[0].text)
        except Exception as e:
            st.warning(f"Could not generate AI recommendation: {e}")

st.divider()
st.caption("FYP Project | Built with scikit-learn / XGBoost + Streamlit + Claude API")
